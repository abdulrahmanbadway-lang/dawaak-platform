export const citiesOf = (gov) => EG.find((g) => g.name === gov)?.cities || [];
const rad = (x) => (x * Math.PI) / 180;
const dist = (a, b) => { const dl = rad(b[0] - a[0]), dg = rad(b[1] - a[1]); const h = Math.sin(dl / 2) ** 2 + Math.cos(rad(a[0])) * Math.cos(rad(b[0])) * Math.sin(dg / 2) ** 2; return 2 * 6371 * Math.asin(Math.sqrt(h)); };
// أقرب محافظة لإحداثيات (أو '' لو برّه مصر أو أبعد من 250 كم من أي نقطة)
export function nearestGov(lat, lng) {
  if (typeof lat !== 'number' || typeof lng !== 'number' || lat < 21.5 || lat > 32 || lng < 24.5 || lng > 36.6) return '';
  let best = '', bd = 1e9;
  for (const g of EG) for (const p of g.a) { const d = dist([lat, lng], p); if (d < bd) { bd = d; best = g.name; } }
  return bd <= 250 ? best : '';
}
