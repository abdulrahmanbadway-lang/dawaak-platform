// ── تذكير الدوا الشهري (محفوظ على جهاز المستخدم فقط، مفتاح لكل حساب) ──
const key = (uid) => 'dw_refill_' + (uid || 'guest');
export function readRefills(uid) {
  try { const l = JSON.parse(localStorage.getItem(key(uid)) || '[]'); return Array.isArray(l) ? l.filter((x) => x && x.id && x.name) : []; } catch { return []; }
}
export function writeRefills(uid, list) {
  try { localStorage.setItem(key(uid), JSON.stringify(list.slice(0, 30))); return true; } catch { return false; }
}
const DAY = 86400000;
// بداية اليوم المحلي (بنتجنب مشاكل الساعات والتوقيت)
export const day0 = (t) => { const d = new Date(t); d.setHours(0, 0, 0, 0); return d.getTime(); };
export const dueDate = (r) => day0(r.start) + Math.max(1, Number(r.days) || 30) * DAY;
export const daysLeft = (r, now = Date.now()) => Math.round((dueDate(r) - day0(now)) / DAY);
// حالة التذكير: late (متأخر) / soon (≤5 أيام) / ok
export const refillState = (r, now) => { const d = daysLeft(r, now); return d < 0 ? 'late' : d <= 5 ? 'soon' : 'ok'; };
export const newRefill = (name, days, now = Date.now()) => ({ id: now.toString(36) + Math.random().toString(36).slice(2, 6), name: String(name).trim().slice(0, 80), days: Math.min(365, Math.max(1, Math.round(Number(days)) || 30)), start: day0(now) });
