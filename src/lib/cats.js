// تصنيف المنتجات: قسم رئيسي + قسم فرعي. القيم المخزّنة في Firestore (products.category / products.sub) نص عربي،
// والعرض بيتترجم بـ trs(). الأقسام القديمة (من الباتش اللي قبل) بتتحوّل تلقائياً عن طريق resolveCat().
export const TREE = [
  { k: 'الأدوية', subs: ['مسكنات وخافضات حرارة', 'برد وكحة', 'معدة وهضم', 'عيون وأذن', 'حساسية', 'مضادات حيوية', 'أدوية الأطفال', 'أدوية جلدية', 'أمراض مزمنة'] },
  { k: 'العناية بالشعر', subs: ['شامبو وبلسم', 'علاج الشعر', 'صبغات الشعر'] },
  { k: 'العناية بالبشرة', subs: ['غسول ومنظفات', 'مرطبات', 'سيروم', 'ماسكات', 'واقي شمس', 'العناية بالعين'] },
  { k: 'الاحتياجات اليومية', subs: ['الاستحمام والجسم', 'العناية بالفم والأسنان', 'العناية النسائية', 'العناية بالرجال', 'أعشاب'] },
  { k: 'الأم والطفل', subs: ['حفاضات', 'العناية بالأم', 'أغذية الأطفال', 'الرضاعة', 'استحمام الطفل'] },
  { k: 'المكياج والإكسسوارات', subs: ['مكياج الوجه', 'مكياج العيون', 'الشفايف', 'الأظافر'] },
  { k: 'المستلزمات الطبية', subs: ['إسعافات أولية', 'أجهزة القياس', 'السكر', 'مساعدات التنفس', 'تسكين الألم'] },
  { k: 'الفيتامينات والمكملات', subs: ['فيتامينات ومعادن', 'مكملات غذائية', 'تخسيس'] },
  { k: 'الصحة الجنسية', subs: ['واقيات', 'مزلقات', 'اختبارات الحمل'] },
];
export const CATS = TREE.map((t) => t.k);
const LEGACY = {
  'مسكنات وخافضات حرارة': ['الأدوية', 'مسكنات وخافضات حرارة'], 'برد وكحة وحساسية': ['الأدوية', 'برد وكحة'], 'المعدة والهضم': ['الأدوية', 'معدة وهضم'],
  'مضادات حيوية': ['الأدوية', 'مضادات حيوية'], 'فيتامينات ومكملات': ['الفيتامينات والمكملات', 'مكملات غذائية'], 'السكر والضغط': ['المستلزمات الطبية', 'السكر'],
  'أجهزة ومستلزمات طبية': ['المستلزمات الطبية', ''],
};
export const subsOf = (c) => TREE.find((t) => t.k === c)?.subs || [];
// بيرجّع [قسم رئيسي, قسم فرعي] لأي منتج (جديد أو قديم)، أو ['', ''] لو من غير قسم
export function resolveCat(p) {
  const c = p?.category || '';
  if (CATS.includes(c)) return [c, subsOf(c).includes(p.sub) ? p.sub : ''];
  return LEGACY[c] || (c === 'العناية بالبشرة' || c === 'الأم والطفل' ? [c, ''] : ['', '']);
}
export const catHue = (c) => Math.max(0, CATS.indexOf(c)) * 40;
